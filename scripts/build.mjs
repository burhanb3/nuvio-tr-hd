import { build } from 'esbuild';
import { readFile, mkdir, writeFile, copyFile, rm } from 'node:fs/promises';
import { resolve, sep, basename } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const manifest = JSON.parse(await readFile(resolve(root, 'manifest.json'), 'utf8'));
const pkg = JSON.parse(await readFile(resolve(root, 'package.json'), 'utf8'));
if (manifest.name !== 'Nuvio TR HD' || manifest.version !== pkg.version || !manifest.scrapers.length) throw new Error('Manifest sürümü/adı tutarsız');
for (const scraper of manifest.scrapers) {
  if (scraper.version !== pkg.version || scraper.filename !== 'providers/nuvio-tr-hd.js') throw new Error('Sağlayıcı yolu/sürümü tutarsız');
}
await mkdir(resolve(root, 'providers'), { recursive: true });
const output = await build({ entryPoints: [resolve(root, 'src/index.cjs')], bundle: true, platform: 'neutral', format: 'cjs',
  target: 'es2020', write: false, legalComments: 'none', charset: 'utf8' });
const code = '// Nuvio TR HD — generated by npm run build; edit src/, not this file.\n' + output.outputFiles[0].text;
if (/\brequire\(["'](?:node:|fs|http|https|path|buffer)/.test(code)) throw new Error('Node bağımlılığı bulundu');
await writeFile(resolve(root, 'providers/nuvio-tr-hd.js'), code);
const dist = resolve(root, 'dist');
if (!dist.startsWith(root + sep) || basename(dist) !== 'dist') throw new Error('Güvensiz paket dizini');
await rm(dist, { force: true, recursive: true });
await mkdir(resolve(root, 'dist/providers'), { recursive: true });
await copyFile(resolve(root, 'manifest.json'), resolve(root, 'dist/manifest.json'));
await writeFile(resolve(root, 'dist/providers/nuvio-tr-hd.js'), code);
await mkdir(resolve(root, 'dist/examples'), { recursive: true });
await copyFile(resolve(root, 'examples/catalog.example.json'), resolve(root, 'dist/examples/catalog.example.json'));
await copyFile(resolve(root, 'site/index.html'), resolve(root, 'dist/index.html'));
console.log(`Nuvio TR HD ${pkg.version}: providers/nuvio-tr-hd.js + dist/ hazır`);
