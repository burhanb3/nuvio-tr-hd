'use strict';
const {safeUrl}=require('../util.cjs');
const {anchors,decodeEntities}=require('./directory.cjs');
const {tagAttributes,sameName,sameOrigin,syntheticFilename}=require('./page-data.cjs');
const {subtitleLanguage}=require('../subtitles.cjs');
const {audioCode}=require('../media/audio.cjs');
const ORIGIN='https://rarefilmm.com',PLAYER='https://ok.ru';
const LEVELS=['mobile','lowest','low','sd','hd','full','quad','ultra'];

function titleMatches(value,target){
  const match=decodeEntities(value).match(/^(.+?)\s*\((\d{4})\)(?:\s+(?:AKA\s+.+|ENG\s+SUBS?))?$/i);
  return !!match && Number(match[2])===target.year && sameName(match[1],target);
}
function searchPages(html,target){
  const result=[];
  for(const block of String(html).matchAll(/<h2\b[^>]*>([\s\S]{0,3000}?)<\/h2>/gi)){
    for(const link of anchors(block[1])){
      const url=sameOrigin(link.href,ORIGIN);
      if(!url||!/^\/\d{4}\/\d{2}\/[a-z0-9-]+\/$/.test(new URL(url).pathname)||!titleMatches(link.text,target))continue;
      if(!result.includes(url))result.push(url);
    }
    if(result.length>=2)break;
  }
  return result.slice(0,2);
}
function articleData(html,target){
  const heading=String(html).match(/<h1\b[^>]*>([\s\S]{0,3000}?)<\/h1>/i)?.[1];
  if(!heading||!titleMatches(heading,target))return null;
  // Only the post body, never comments, related films or a sidebar player.
  const body=String(html).match(/<article\b[^>]*>([\s\S]{0,70000}?)<\/article>/i)?.[1];
  if(!body)return null;
  const ids=anchors(body).map(a=>a.href.match(/^https?:\/\/(?:www\.)?imdb\.com\/title\/(tt\d+)(?:$|[/?#])/i)?.[1]).filter(Boolean);
  if(target.imdbId&&ids.some(id=>id!==target.imdbId))return null;
  const embeds=[...body.matchAll(/<iframe\b[^>]*>/gi)].map(m=>safeUrl(tagAttributes(m[0]).src,ORIGIN));
  const embed=embeds.find(url=>url&&new URL(url).origin===PLAYER&&/^\/videoembed\/\d{5,20}$/.test(new URL(url).pathname));
  if(!embed)return null;
  const text=decodeEntities(body),sub=text.match(/\bSubtitles:\s*([^|\r\n]{0,150})/i)?.[1]||'';
  const burned=/\bEnglish\s*\(hard(?:[,)]|\s)/i.test(sub)?'en':null;
  const declared=text.match(/\bLanguages?:\s*([^|\r\n]{1,140})\|/i)?.[1]||'';
  const claimedAudioLanguages=[...new Set(declared.split(',').map(s=>audioCode(s)||({'irish gaelic':'ga',kurdish:'ku'})[s.trim().toLowerCase()]).filter(Boolean))];
  return {embed:PLAYER+new URL(embed).pathname,burnedSubtitleLanguage:burned,claimedAudioLanguages};
}
function mediaUrl(value){
  const url=safeUrl(value,PLAYER+'/');
  return url&&/^(?:[a-z0-9-]+\.)+(?:vkuser\.net|okcdn\.ru|mycdn\.me)$/i.test(new URL(url).hostname)?url:null;
}
function playerData(html,embed,target){
  const id=new URL(embed).pathname.split('/').pop();
  for(const tag of String(html).matchAll(/<div\b[^>]*>/gi)){
    const attr=tagAttributes(tag[0]);
    if(attr['data-movie-id']!==id||!attr['data-options'])continue;
    try{
      const options=JSON.parse(decodeEntities(attr['data-options']));
      const raw=options.flashvars?.metadata,meta=typeof raw==='string'?JSON.parse(raw):raw;
      const movie=meta?.movie;
      const title=String(movie?.title||'').replace(/^\[(?:HD\/)?\d{3,4}p\]\s*/i,'');
      if(meta?.provider!=='UPLOADED_ODKL'||String(movie?.id)!==id||String(meta.ownerMovieId)!==id||movie.status!=='OK'||
        movie.isLive||movie.isClip||movie.notPublished||!titleMatches(title,target)||!(Number(movie.duration)>0))return null;
      const expected=target.runtimeMinutes*60;
      if(expected>0&&Math.abs(Number(movie.duration)-expected)>expected*0.1)return null;
      const tracks=Array.isArray(movie.subtitleTracks)?movie.subtitleTracks:[];
      const subtitles=tracks.slice(0,12).filter(t=>t&&t.autogenerated!==true&&subtitleLanguage(t.language)&&mediaUrl(t.url))
        .map(t=>({url:mediaUrl(t.url),language:subtitleLanguage(t.language),_scope:'paired',identity:target,headers:{Referer:PLAYER+'/'}}));
      const files=(Array.isArray(meta.videos)?meta.videos:[]).filter(v=>v&&LEVELS.includes(v.name)&&v.disallowed!==true&&mediaUrl(v.url));
      const levels=LEVELS.filter(level=>files.some(f=>f.name===level));
      // Probe high, small and middle encodes within three slots. Do not use
      // metadata dimensions for every variant: actual file pixels win later.
      const usable=levels.filter(l=>l!=='mobile');
      const selected=usable.length?usable:levels;
      const order=[selected[selected.length-1],selected[0],selected[Math.floor(selected.length/2)]];
      const seen=new Set();
      const videos=order.map(level=>files.find(f=>f.name===level)).filter(f=>f&&!seen.has(f.url)&&seen.add(f.url));
      return {videos,subtitles};
    }catch{return null;}
  }
  return null;
}
async function scanRareFilmm(http,target){
  if(target.type!=='movie'||target.isAnime)return [];
  let found;
  for(const name of [...new Set([target.originalTitle,...(target.searchTitles||[])])].slice(0,2)){
    if(http.expired())break;
    const search=await http.text(ORIGIN+'/?s='+encodeURIComponent(name));
    for(const url of search?searchPages(search.text,target):[]){
      const page=await http.text(url),article=page&&articleData(page.text,target);
      if(article){found=article;break;}
      if(http.expired())break;
    }
    if(found)break;
  }
  if(!found||http.expired())return [];
  const player=await http.text(found.embed,{headers:{Referer:ORIGIN+'/'}});
  const data=player&&playerData(player.text,found.embed,target);
  if(!data)return [];
  return data.videos.map(entry=>({url:mediaUrl(entry.url),source:'RareFilmm',headers:{Referer:PLAYER+'/'},identity:target,identityConfidence:90,
    filename:syntheticFilename(target)+'.mp4',filenameSynthetic:true,requireDuration:true,durationTolerance:0.1,
    claimedAudioLanguages:found.claimedAudioLanguages,
    ...(found.burnedSubtitleLanguage?{burnedSubtitleLanguage:found.burnedSubtitleLanguage}:{}),subtitles:data.subtitles}));
}
module.exports={scanRareFilmm,titleMatches,searchPages,articleData,playerData,mediaUrl};
